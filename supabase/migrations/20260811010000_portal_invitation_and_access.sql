create table public.portal_invitations (
  id uuid primary key default gen_random_uuid(),
  token_hash bytea not null unique,
  portal_role text not null check (portal_role in ('homeowner', 'contractor')),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  lead_id bigint references public.leads(id) on delete cascade,
  contractor_id bigint references public.contractors(id) on delete cascade,
  intended_email text not null,
  issued_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  accepted_by uuid references auth.users(id),
  revoked_at timestamptz,
  check (
    (portal_role = 'homeowner' and lead_id is not null and contractor_id is null)
    or (portal_role = 'contractor' and contractor_id is not null and lead_id is null)
  )
);

create index portal_invitations_workspace_idx on public.portal_invitations(workspace_id, created_at desc);
create index portal_invitations_open_idx on public.portal_invitations(expires_at)
  where accepted_at is null and revoked_at is null;

create table public.homeowner_portal_links (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  lead_id bigint not null references public.leads(id) on delete cascade,
  invitation_id uuid not null unique references public.portal_invitations(id),
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

create unique index homeowner_portal_links_active_unique
  on public.homeowner_portal_links(user_id, workspace_id, lead_id) where revoked_at is null;
create index homeowner_portal_links_user_idx
  on public.homeowner_portal_links(user_id, workspace_id) where revoked_at is null;

create table public.contractor_portal_links (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  contractor_id bigint not null references public.contractors(id) on delete cascade,
  invitation_id uuid not null unique references public.portal_invitations(id),
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);

create unique index contractor_portal_links_active_unique
  on public.contractor_portal_links(user_id, workspace_id, contractor_id) where revoked_at is null;
create index contractor_portal_links_user_idx
  on public.contractor_portal_links(user_id, workspace_id, contractor_id) where revoked_at is null;

create table public.portal_access_events (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id),
  portal_role text not null check (portal_role in ('homeowner', 'contractor')),
  action text not null,
  entity_type text not null,
  entity_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index portal_access_events_workspace_idx
  on public.portal_access_events(workspace_id, created_at desc);
create index portal_access_events_actor_idx
  on public.portal_access_events(actor_user_id, created_at desc);

alter table public.portal_invitations enable row level security;
alter table public.homeowner_portal_links enable row level security;
alter table public.contractor_portal_links enable row level security;
alter table public.portal_access_events enable row level security;

create policy portal_invitations_workspace_select on public.portal_invitations
for select to authenticated using (
  exists (select 1 from public.workspace_members wm
    where wm.workspace_id = portal_invitations.workspace_id and wm.user_id = auth.uid())
);

create policy homeowner_links_self_select on public.homeowner_portal_links
for select to authenticated using (user_id = auth.uid() and revoked_at is null);
create policy homeowner_links_workspace_select on public.homeowner_portal_links
for select to authenticated using (
  exists (select 1 from public.workspace_members wm
    where wm.workspace_id = homeowner_portal_links.workspace_id and wm.user_id = auth.uid())
);

create policy contractor_links_self_select on public.contractor_portal_links
for select to authenticated using (user_id = auth.uid() and revoked_at is null);
create policy contractor_links_workspace_select on public.contractor_portal_links
for select to authenticated using (
  exists (select 1 from public.workspace_members wm
    where wm.workspace_id = contractor_portal_links.workspace_id and wm.user_id = auth.uid())
);

create policy portal_events_actor_select on public.portal_access_events
for select to authenticated using (actor_user_id = auth.uid());
create policy portal_events_workspace_select on public.portal_access_events
for select to authenticated using (
  exists (select 1 from public.workspace_members wm
    where wm.workspace_id = portal_access_events.workspace_id and wm.user_id = auth.uid())
